// MAP_DATA-first Generated membership, Atlas enrichment, and duplicate ID protection.
const fs=require('fs'),vm=require('vm'),zlib=require('zlib'),assert=require('assert');
const h=fs.readFileSync('examples/WIZAMAP_FIXED_UI.html','utf8'),packed=h.match(/<script[^>]*id="wzw-embedded-atlas"[^>]*>(.*?)<\/script>/s)[1];
const DATA=JSON.parse(zlib.gunzipSync(Buffer.from(packed,'base64'))),ATLAS=JSON.parse(fs.readFileSync('assets/atlas.json')),VOCAB=JSON.parse(fs.readFileSync('assets/vocabulary.json')),RECIPES=JSON.parse(fs.readFileSync('assets/recipes.json'));
const ctx=vm.createContext({DATA,ATLAS,VOCAB,RECIPES,KEYS:['unknown','adult']});
vm.runInContext(['contract','props','resolver'].map(n=>fs.readFileSync('src/'+n+'.js','utf8')).join('\n')+';globalThis.test=x=>{const d=normalize(x);return{d,scene:resolve(d)}}',ctx);
const kitchen='AU-PC-HOME:f1-kitchen',living='AU-PC-HOME:f1-living',garden='AU-PC-HOME:f1-rear-porch-garden';
const room=(id,name,type)=>({id,name,type});
const payload=(places,pcPlace=kitchen,extra={})=>({schemaVersion:'2.0.0',atlasAnchor:'AU-PC-HOME',pcPlace,pcSpot:'inside',places,actors:[{name:'Jude',isPC:true,placeId:pcPlace,spot:'inside'}],events:[],...extra});
let r=ctx.test(payload([room(kitchen,'Gian bếp','KITCHEN'),room(living,'Phòng khách','LOUNGE')]));
assert.equal(r.scene.places.length,2,'two requested rooms only, not all 16 Atlas rooms');
assert.equal(r.scene.places[0].id,kitchen);assert.equal(r.scene.places[0].name,'Gian bếp');
assert.equal(r.scene.places[1].id,living);assert.equal(r.scene.places[1].name,'Phòng khách');
assert(r.scene.places[0].interiorPlan,'existing room inherits Atlas geometry/furniture formula');
assert.equal(r.scene.places[0].type,'KITCHEN');
r=ctx.test(payload([room(kitchen,'Gian bếp','KITCHEN')]));
assert.equal(r.scene.places.length,1,'removing a MAP_DATA room removes it from the rendered scene');
r=ctx.test(payload([room(kitchen,'Gian bếp','KITCHEN'),room(kitchen,'Kitchen','KITCHEN')]));
assert.equal(r.scene.places.length,1,'same native ID in English/Vietnamese must not add a room');
assert(r.d.diagnostics.some(x=>x.includes('duplicate-place-id:')),'duplicate ID is diagnosed');
r=ctx.test(payload([room(kitchen,'Gian bếp cải tạo','LOUNGE')]));
assert.equal(r.scene.places.length,1);
assert.equal(r.scene.places[0].type,'LOUNGE','RP type override beats Atlas');
assert.equal(r.scene.places[0].name,'Gian bếp cải tạo','RP Vietnamese label beats Atlas');
r=ctx.test(payload([room(kitchen,'Gian bếp','KITCHEN'),room('rp:guest-room','Phòng khách mới','BEDROOM')]));
assert.equal(r.scene.places.length,2,'RP-established new room allowed alongside Atlas room');
assert.equal(r.scene.places[1].id,'rp:guest-room');
r=ctx.test(payload([room(kitchen,'Gian bếp','KITCHEN')],kitchen,{events:[{title:'Khám phá',placeId:'rp:ghost-room'}]}));
assert.equal(r.scene.places.length,1,'unresolved event must not create a phantom room');
assert(r.d.diagnostics.some(x=>x.startsWith('unresolved-location:')||x.startsWith('unresolved-location-not-in-map-data:')));
r=ctx.test(payload([room(garden,'Vườn sau','OUT_GARDEN')],garden));
assert.equal(r.scene.places.length,1);assert.equal(r.scene.places[0].type,'OUT_GARDEN','RP recipe is authoritative over Atlas');
console.log('PASS MAP_DATA-first Generated scenes, add/remove, native ID dedup, RP overrides, missing ref');
